/**
 * Lookup a single word in the dictionary (case-insensitive)
 */
export function lookup(word) {
  if (!word) return null
  const clean = word.toLowerCase().replace(/[.,;:!?'"()\[\]{}—–]/g, '').replace(/'/g, '').trim()
  if (!clean) return null
  return DICTIONARY[clean] || null
}

/**
 * Try to find a compound phrase starting from the given index in a word array.
 * Returns { phrase, translation, wordCount } or null.
 */
export function lookupCompound(words, startIndex) {
  // Try longest match first (4 words → 2 words)
  for (let len = Math.min(4, words.length - startIndex); len >= 2; len--) {
    const phrase = words.slice(startIndex, startIndex + len)
      .map(w => w.toLowerCase().replace(/[.,;:!?'"()\[\]{}—–-]/g, '').replace(/'/g, '').trim())
      .join(' ')
    if (COMPOUNDS[phrase]) {
      return { phrase, translation: COMPOUNDS[phrase], wordCount: len }
    }
  }
  return null
}

/**
 * Check if a word exists in the dictionary
 */
export function hasDefinition(word) {
  return lookup(word) !== null
}

